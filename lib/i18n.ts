export type Locale = 'en' | 'es';
export type Strings = typeof en;
export const strings: Record<Locale, Strings> = { en, es };

const tag = (l: Locale) => (l === 'es' ? 'es-MX' : 'en-US');

export function fmtDate(ymd: string, l: Locale, opts: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(tag(l), { timeZone: 'UTC', ...opts }).format(new Date(`${ymd}T00:00:00Z`));
}

export const longDate = (ymd: string, l: Locale) => fmtDate(ymd, l, { weekday: 'long', month: 'long', day: 'numeric' });
export const dow = (ymd: string, l: Locale) => fmtDate(ymd, l, { weekday: 'short' }).replace('.', '');
export const dayNum = (ymd: string) => String(Number(ymd.slice(8, 10)));
