export type Locale = 'en' | 'es';
export type Strings = typeof en;
export const strings: Record<Locale, Strings> = { en, es };

const tag = (l: Locale) => (l === 'es' ? 'es-MX' : 'en-US');

export function fmtDate(ymd: string, l: Locale, opts: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(tag(l), { timeZone: 'UTC', ...opts }).format(new Date(`${ymd}T00:00:00Z`));
}

export const longDate = (ymd: string, l: Locale) => fmtDate(ymd, l, { weekday: 'long', month: 'long', day: 'numeric' });
export const dow = (ymd: string, l: Locale) => fmtDate(ymd, l, { weekday: 'short' }).replace('.', '');
export const dayNum = (ymd: string) => String(Number(ymd.slice(8, 10)));
export const weekdayName = (ymd: string, l: Locale) => fmtDate(ymd, l, { weekday: 'long' });
export const monthDay = (ymd: string, l: Locale) => fmtDate(ymd, l, { month: 'long', day: 'numeric' });

// "Plan {day}" + { day: 'Tuesday' } → "Plan Tuesday"
export function fill(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

// Hours as a person says them, for the notebook: "half an hour", "7½ hours".
export function hoursSaid(minutes: number, l: Locale) {
  const es = l === 'es';
  if (minutes < 60 && minutes % 30 !== 0) return es ? `${minutes} minutos` : `${minutes} minutes`;
  if (minutes === 30) return es ? 'media hora' : 'half an hour';
  const whole = Math.floor(minutes / 60);
  const part = { 0: '', 15: '¼', 30: '½', 45: '¾' }[minutes % 60 as 0 | 15 | 30 | 45];
  if (part === undefined) return es ? `${(minutes / 60).toFixed(1)} horas` : `${(minutes / 60).toFixed(1)} hours`;
  if (whole === 1 && !part) return es ? 'una hora' : 'one hour';
  return es ? `${whole || ''}${part} horas` : `${whole || ''}${part} hours`;
}
